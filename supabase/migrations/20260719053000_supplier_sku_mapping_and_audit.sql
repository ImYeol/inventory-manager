create or replace function public.reject_supplier_sku_mapping_audit_mutation() returns trigger language plpgsql set search_path=public as $$ begin raise exception 'immutable_supplier_sku_mapping_audit'; end; $$;
create trigger supplier_sku_mapping_audits_immutable before update or delete on public.supplier_sku_mapping_audits for each row execute function public.reject_supplier_sku_mapping_audit_mutation();

create or replace function private.write_supplier_sku_mapping_audit(p_action text,p_supplier_id bigint,p_raw text,p_normalized text,p_previous bigint,p_new bigint,p_reason text)
returns void language plpgsql security definer set search_path=private,public as $$
declare v_user uuid:=auth.uid(); v_supplier text; v_old text; v_new text;
begin
 select name into v_supplier from public.factories where id=p_supplier_id and user_id=v_user;
 select seller_sku into v_old from public.product_variants where id=p_previous and user_id=v_user;
 select seller_sku into v_new from public.product_variants where id=p_new and user_id=v_user;
 insert into public.supplier_sku_mapping_audits(user_id,actor_id,supplier_id,supplier_name_snapshot,raw_external_sku,normalized_external_sku,action,previous_product_variant_id,previous_seller_sku_snapshot,new_product_variant_id,new_seller_sku_snapshot,reason)
 values(v_user,v_user,p_supplier_id,v_supplier,p_raw,p_normalized,p_action,p_previous,v_old,p_new,v_new,nullif(btrim(p_reason),''));
end; $$;

create or replace function public.confirm_supplier_sku_mapping(p_supplier_id bigint,p_external_sku text,p_product_variant_id bigint,p_source_row_ids bigint[] default '{}')
returns bigint language plpgsql security definer set search_path=private,public as $$
declare v_user uuid:=auth.uid(); v_normalized text:=private.normalize_supplier_external_sku(p_external_sku); v_existing public.supplier_sku_links%rowtype; v_id bigint;
begin
 if v_user is null then raise exception 'Authentication is required.'; end if;
 if v_normalized='' then raise exception 'External SKU is required.'; end if;
 if not exists(select 1 from public.factories where id=p_supplier_id and user_id=v_user) then raise exception 'Supplier not found.'; end if;
 if not exists(select 1 from public.product_variants where id=p_product_variant_id and user_id=v_user) then raise exception 'Product variant not found.'; end if;
 select * into v_existing from public.supplier_sku_links where user_id=v_user and supplier_id=p_supplier_id and normalized_external_sku=v_normalized and is_active for update;
 if found then
   if v_existing.product_variant_id=p_product_variant_id then raise exception 'Duplicate active supplier SKU mapping.'; end if;
   raise exception 'Active supplier SKU mapping conflicts; reassign it explicitly.';
 end if;
 insert into public.supplier_sku_links(user_id,supplier_id,template,template_id,external_sku,normalized_external_sku,product_variant_id,received_at,is_active) values(v_user,p_supplier_id,'',null,p_external_sku,v_normalized,p_product_variant_id,timezone('utc',now()),true) returning id into v_id;
 perform private.write_supplier_sku_mapping_audit('CONFIRMED',p_supplier_id,p_external_sku,v_normalized,null,p_product_variant_id,null);
 if cardinality(p_source_row_ids)>0 then
   perform set_config('app.supplier_mapping_write','on',true);
   update public.inbound_import_source_rows sr set product_variant_id=p_product_variant_id,seller_sku_snapshot=pv.seller_sku,product_name_snapshot=m.name,option_name_snapshot=concat_ws(' / ',c.name,s.name)
   from public.product_variants pv join public.models m on m.id=pv.model_id and m.user_id=pv.user_id join public.sizes s on s.id=pv.size_id and s.user_id=pv.user_id join public.colors c on c.id=pv.color_id and c.user_id=pv.user_id
   where sr.id=any(p_source_row_ids) and sr.user_id=v_user and pv.id=p_product_variant_id and pv.user_id=v_user;
 end if;
 return v_id;
end; $$;

create or replace function public.reassign_supplier_sku_mapping(p_supplier_id bigint,p_external_sku text,p_product_variant_id bigint,p_reason text)
returns bigint language plpgsql security definer set search_path=private,public as $$
declare v_user uuid:=auth.uid(); v_normalized text:=private.normalize_supplier_external_sku(p_external_sku); v_old public.supplier_sku_links%rowtype; v_id bigint;
begin
 if nullif(btrim(p_reason),'') is null then raise exception 'A reassign reason is required.'; end if;
 select * into v_old from public.supplier_sku_links where user_id=v_user and supplier_id=p_supplier_id and normalized_external_sku=v_normalized and is_active for update;
 if not found then raise exception 'Active supplier SKU mapping not found.'; end if;
 if not exists(select 1 from public.product_variants where id=p_product_variant_id and user_id=v_user) then raise exception 'Product variant not found.'; end if;
 if v_old.product_variant_id=p_product_variant_id then raise exception 'Supplier SKU already maps to this ProductVariant.'; end if;
 update public.supplier_sku_links set is_active=false,deactivated_at=timezone('utc',now()),deactivation_reason=p_reason where id=v_old.id;
 insert into public.supplier_sku_links(user_id,supplier_id,template,external_sku,normalized_external_sku,product_variant_id,received_at,is_active) values(v_user,p_supplier_id,'',p_external_sku,v_normalized,p_product_variant_id,timezone('utc',now()),true) returning id into v_id;
 perform private.write_supplier_sku_mapping_audit('REASSIGNED',p_supplier_id,p_external_sku,v_normalized,v_old.product_variant_id,p_product_variant_id,p_reason); return v_id;
end; $$;

create or replace function public.deactivate_supplier_sku_mapping(p_supplier_id bigint,p_external_sku text,p_reason text)
returns void language plpgsql security definer set search_path=private,public as $$
declare v_user uuid:=auth.uid(); v_normalized text:=private.normalize_supplier_external_sku(p_external_sku); v_old public.supplier_sku_links%rowtype;
begin
 if nullif(btrim(p_reason),'') is null then raise exception 'A deactivation reason is required.'; end if;
 select * into v_old from public.supplier_sku_links where user_id=v_user and supplier_id=p_supplier_id and normalized_external_sku=v_normalized and is_active for update;
 if not found then raise exception 'Active supplier SKU mapping not found.'; end if;
 update public.supplier_sku_links set is_active=false,deactivated_at=timezone('utc',now()),deactivation_reason=p_reason where id=v_old.id;
 perform private.write_supplier_sku_mapping_audit('DEACTIVATED',p_supplier_id,p_external_sku,v_normalized,v_old.product_variant_id,null,p_reason);
end; $$;
grant execute on function public.confirm_supplier_sku_mapping(bigint,text,bigint,bigint[]),public.reassign_supplier_sku_mapping(bigint,text,bigint,text),public.deactivate_supplier_sku_mapping(bigint,text,text) to authenticated;
revoke all on function private.normalize_supplier_external_sku(text),private.write_supplier_sku_mapping_audit(text,bigint,text,text,bigint,bigint,text) from public,anon,authenticated;

