create table public.supplier_sku_mapping_audits (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete restrict,
  supplier_id bigint not null, supplier_name_snapshot text,
  raw_external_sku text not null, normalized_external_sku text not null,
  action text not null check (action in ('CONFIRMED','REASSIGNED','DEACTIVATED','LEGACY_CONFLICT')),
  previous_product_variant_id bigint, previous_seller_sku_snapshot text,
  new_product_variant_id bigint, new_seller_sku_snapshot text,
  reason text, created_at timestamptz not null default timezone('utc',now()),
  foreign key (supplier_id,user_id) references public.factories(id,user_id) on delete restrict
);
create index supplier_sku_links_active_exact_idx on public.supplier_sku_links(user_id,supplier_id,normalized_external_sku) where is_active;
create unique index supplier_sku_links_one_active_exact_idx on public.supplier_sku_links(user_id,supplier_id,normalized_external_sku) where is_active;
create index supplier_sku_mapping_audits_owner_supplier_created_idx on public.supplier_sku_mapping_audits(user_id,supplier_id,created_at desc);

-- A collapsed legacy key is retained only when every old mapping agrees.
with conflicts as (
  select user_id,supplier_id,normalized_external_sku
  from public.supplier_sku_links where is_active group by 1,2,3 having count(distinct product_variant_id) > 1
), deactivated as (
  update public.supplier_sku_links l set is_active=false,deactivated_at=timezone('utc',now()),deactivation_reason='Legacy template mappings conflict; explicit resolution required.'
  from conflicts c where l.user_id=c.user_id and l.supplier_id=c.supplier_id and l.normalized_external_sku=c.normalized_external_sku and l.is_active
  returning l.*
)
insert into public.supplier_sku_mapping_audits(user_id,actor_id,supplier_id,supplier_name_snapshot,raw_external_sku,normalized_external_sku,action,reason)
select d.user_id,d.user_id,d.supplier_id,f.name,d.external_sku,d.normalized_external_sku,'LEGACY_CONFLICT','Legacy template mappings conflict; explicit resolution required.'
from deactivated d join public.factories f on f.id=d.supplier_id and f.user_id=d.user_id;

-- Same-target legacy duplicates collapse to one active row without guessing.
with ranked as (
  select id,row_number() over(partition by user_id,supplier_id,normalized_external_sku order by received_at desc,id desc) as position
  from public.supplier_sku_links where is_active
)
update public.supplier_sku_links l set is_active=false,deactivated_at=timezone('utc',now()),deactivation_reason='Superseded duplicate legacy mapping.'
from ranked r where l.id=r.id and r.position>1;

