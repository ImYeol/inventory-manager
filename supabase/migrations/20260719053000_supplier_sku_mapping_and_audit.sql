create or replace function public.reject_canonical_evidence_mutation() returns trigger language plpgsql set search_path=public as $$ begin if current_setting('app.supplier_mapping_write',true)='on' and tg_table_name='inbound_import_source_rows' then return new; end if; raise exception 'immutable_canonical_evidence'; end; $$;
