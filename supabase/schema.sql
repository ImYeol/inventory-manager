create or replace function public.receive_inbound_draft_rows(p_draft_id bigint, p_rows jsonb)
returns void language plpgsql security invoker set search_path = '' as $$
declare
  v_user_id uuid := auth.uid(); v_row jsonb; v_draft public.inbound_drafts%rowtype; v_item public.inbound_draft_rows%rowtype;
  v_variant public.product_variants%rowtype; v_quantity integer; v_remaining integer; v_open integer;
begin
  if v_user_id is null then raise exception 'Authentication is required.'; end if;
  if jsonb_typeof(p_rows) is distinct from 'array' then raise exception 'p_rows must be a JSON array.'; end if;
  select * into v_draft from public.inbound_drafts where id = p_draft_id and user_id = v_user_id for update;
  if not found or v_draft.status = 'received' then raise exception 'Inbound draft cannot be received.'; end if;
  for v_row in select * from jsonb_array_elements(p_rows) loop
    select * into v_item from public.inbound_draft_rows where id = (v_row ->> 'row_id')::bigint and inbound_draft_id = p_draft_id and user_id = v_user_id for update;
    if not found then raise exception 'Inbound draft row not found.'; end if;
    if v_item.product_variant_id is null then raise exception 'Unmatched inbound rows cannot be received.'; end if;
    v_quantity := (v_row ->> 'quantity')::integer; v_remaining := v_item.quantity - v_item.received_quantity;
    if v_quantity is null or v_quantity <= 0 or v_quantity > v_remaining then raise exception 'Receive quantity is invalid.'; end if;
    select * into v_variant from public.product_variants where id = v_item.product_variant_id and user_id = v_user_id;
    if not found then raise exception 'Assigned internal SKU not found.'; end if;
    update public.inbound_draft_rows set received_quantity = received_quantity + v_quantity, updated_at = timezone('utc', now()) where id = v_item.id;
    insert into public.inventory (user_id, model_id, size_id, color_id, warehouse_id, quantity) values (v_user_id, v_variant.model_id, v_variant.size_id, v_variant.color_id, v_item.warehouse_id, v_quantity)
      on conflict (user_id, model_id, size_id, color_id, warehouse_id) do update set quantity = public.inventory.quantity + excluded.quantity, updated_at = timezone('utc', now());
    insert into public.transactions (user_id, date, model_id, size_id, color_id, type, quantity, warehouse_id, source_channel, reference_type, reference_id, memo)
      values (v_user_id, current_date, v_variant.model_id, v_variant.size_id, v_variant.color_id, 'INBOUND', v_quantity, v_item.warehouse_id, 'inbound-draft', 'inbound_draft_row', v_item.id, '검수 입고');
    insert into public.inventory_sync_outbox (user_id, channel_product_ref_id, target_quantity, status, last_error, requested_at, updated_at)
      select v_user_id, ref.id, greatest(coalesce(sum(inv.quantity), 0) - coalesce((select sum(quantity) from public.inventory_reservations where user_id = v_user_id and product_variant_id = v_variant.id and status = 'active'), 0), 0), 'required', '동기화 필요: 현재 provider는 재고 수량 쓰기를 지원하지 않습니다.', timezone('utc', now()), timezone('utc', now())
      from public.channel_product_refs ref left join public.inventory inv on inv.user_id = v_user_id and inv.model_id = v_variant.model_id and inv.size_id = v_variant.size_id and inv.color_id = v_variant.color_id
      where ref.user_id = v_user_id and ref.variant_id = v_variant.id group by ref.id
      on conflict (user_id, channel_product_ref_id) do update set target_quantity = excluded.target_quantity, status = 'required', last_error = excluded.last_error, requested_at = excluded.requested_at, updated_at = excluded.updated_at;
  end loop;
  select count(*) into v_open from public.inbound_draft_rows where inbound_draft_id = p_draft_id and user_id = v_user_id and received_quantity < quantity;
  update public.inbound_drafts set status = case when v_open = 0 then 'received' else 'partial' end, updated_at = timezone('utc', now()) where id = p_draft_id and user_id = v_user_id;
end;
$$;

