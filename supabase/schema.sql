create or replace function public.transfer_inventory_between_warehouses(p_transfer jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_model_id bigint := (p_transfer ->> 'model_id')::bigint;
  v_size_id bigint := (p_transfer ->> 'size_id')::bigint;
  v_color_id bigint := (p_transfer ->> 'color_id')::bigint;
  v_from_warehouse_id bigint := (p_transfer ->> 'from_warehouse_id')::bigint;
  v_to_warehouse_id bigint := (p_transfer ->> 'to_warehouse_id')::bigint;
  v_quantity integer := (p_transfer ->> 'quantity')::integer;
  v_date date := (p_transfer ->> 'date')::date;
  v_reason text := btrim(coalesce(p_transfer ->> 'reason', ''));
  v_source public.inventory%rowtype;
  v_variant_id bigint;
  v_on_hand integer;
  v_committed integer;
  v_target integer;
  v_ref record;
  v_now timestamptz := timezone('utc', now());
  v_sync_error text := '동기화 필요: 현재 provider는 재고 수량 쓰기를 지원하지 않습니다.';
  v_memo text;
begin
  if v_user_id is null then raise exception 'Authentication is required.'; end if;
  if p_transfer is null or jsonb_typeof(p_transfer) <> 'object' then raise exception 'p_transfer must be an object.'; end if;
  if v_model_id is null or v_size_id is null or v_color_id is null or v_from_warehouse_id is null or v_to_warehouse_id is null then raise exception 'Product option and warehouses are required.'; end if;
  if v_from_warehouse_id = v_to_warehouse_id then raise exception 'Source and destination warehouses must differ.'; end if;
  if v_quantity is null or v_quantity <= 0 then raise exception 'Quantity must be greater than zero.'; end if;
  if v_date is null or v_reason = '' then raise exception 'Date and reason are required.'; end if;
  if not exists (select 1 from public.warehouses where id = v_from_warehouse_id and user_id = v_user_id)
    or not exists (select 1 from public.warehouses where id = v_to_warehouse_id and user_id = v_user_id) then raise exception 'Warehouse not found.'; end if;

  select * into v_source from public.inventory where user_id = v_user_id and model_id = v_model_id and size_id = v_size_id and color_id = v_color_id and warehouse_id = v_from_warehouse_id for update;
  if not found or v_source.quantity < v_quantity then raise exception 'Insufficient on-hand inventory.'; end if;

  update public.inventory set quantity = quantity - v_quantity, updated_at = v_now where id = v_source.id;
  insert into public.inventory (user_id, model_id, size_id, color_id, warehouse_id, quantity)
  values (v_user_id, v_model_id, v_size_id, v_color_id, v_to_warehouse_id, v_quantity)
  on conflict (user_id, model_id, size_id, color_id, warehouse_id) do update set quantity = public.inventory.quantity + excluded.quantity, updated_at = v_now;

  v_memo := format('창고 이동: %s → %s / %s', v_from_warehouse_id, v_to_warehouse_id, v_reason);
  insert into public.transactions (user_id, date, model_id, size_id, color_id, type, quantity, warehouse_id, source_channel, reference_type, memo)
  values
    (v_user_id, v_date, v_model_id, v_size_id, v_color_id, 'OUTBOUND', v_quantity, v_from_warehouse_id, 'manual', 'warehouse_transfer_outbound', v_memo),
    (v_user_id, v_date, v_model_id, v_size_id, v_color_id, 'INBOUND', v_quantity, v_to_warehouse_id, 'manual', 'warehouse_transfer_inbound', v_memo);

  select id into v_variant_id from public.product_variants where user_id = v_user_id and model_id = v_model_id and size_id = v_size_id and color_id = v_color_id;
  if found then
    select coalesce(sum(quantity), 0) into v_on_hand from public.inventory where user_id = v_user_id and model_id = v_model_id and size_id = v_size_id and color_id = v_color_id;
    select coalesce(sum(quantity), 0) into v_committed from public.inventory_reservations where user_id = v_user_id and product_variant_id = v_variant_id and status = 'active';
    v_target := greatest(0, v_on_hand - v_committed);
    for v_ref in select id from public.channel_product_refs where user_id = v_user_id and variant_id = v_variant_id loop
      update public.channel_product_refs set sync_target_quantity = v_target, sync_status = 'required', last_sync_error = v_sync_error, updated_at = v_now where id = v_ref.id and user_id = v_user_id;
      insert into public.inventory_sync_outbox (user_id, channel_product_ref_id, target_quantity, status, last_error, requested_at, updated_at)
      values (v_user_id, v_ref.id, v_target, 'required', v_sync_error, v_now, v_now)
      on conflict (user_id, channel_product_ref_id) do update set target_quantity = excluded.target_quantity, status = 'required', last_error = excluded.last_error, requested_at = excluded.requested_at, updated_at = excluded.updated_at;
    end loop;
  end if;
end;
$$;

create or replace function public.revert_inventory_transaction(
  p_transaction_id bigint,
  p_memo text default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_transaction public.transactions%rowtype;
  v_previous public.transactions%rowtype;
  v_new_type public.transaction_type_value;
  v_new_quantity integer;
  v_current_quantity integer;
  v_running_quantity integer := 0;
  v_new_transaction_id bigint;
  v_normalized_memo text := nullif(btrim(p_memo), '');
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  select *
  into v_transaction
  from public.transactions
  where id = p_transaction_id
    and user_id = v_user_id
  for update;

  if not found then
    raise exception 'Transaction not found.';
  end if;

  if v_transaction.type not in ('INBOUND', 'OUTBOUND', 'ADJUSTMENT') then
    raise exception 'Unsupported transaction type.';
  end if;

  if v_transaction.source_channel = 'csv' then
    raise exception 'CSV 반영 이력은 되돌릴 수 없습니다.';
  end if;

  if v_transaction.source_channel = 'factory-arrival' then
    raise exception '예정입고 반영 이력은 되돌릴 수 없습니다.';
  end if;

  if v_transaction.reference_type is not null or v_transaction.reference_id is not null then
    raise exception '이미 시스템 참조가 있는 행은 되돌릴 수 없습니다.';
  end if;

  if v_transaction.source_channel is not null and v_transaction.source_channel <> 'manual' then
    raise exception '수동 등록 이력만 되돌릴 수 있습니다.';
  end if;

  if exists (
    select 1
    from public.transactions newer
    where newer.user_id = v_user_id
      and newer.model_id = v_transaction.model_id
      and newer.size_id = v_transaction.size_id
      and newer.color_id = v_transaction.color_id
      and newer.warehouse_id = v_transaction.warehouse_id
      and (
        newer.date > v_transaction.date
        or (newer.date = v_transaction.date and newer.created_at > v_transaction.created_at)
        or (
          newer.date = v_transaction.date
          and newer.created_at = v_transaction.created_at
          and newer.id > v_transaction.id
        )
      )
  ) then
    raise exception '후속 이력 있음';
  end if;

  if v_transaction.type = 'INBOUND' then
    v_new_type := 'OUTBOUND';
    v_new_quantity := v_transaction.quantity;

    select quantity
    into v_current_quantity
    from public.inventory
    where user_id = v_user_id
      and model_id = v_transaction.model_id
      and size_id = v_transaction.size_id
      and color_id = v_transaction.color_id
      and warehouse_id = v_transaction.warehouse_id
    for update;

    if not found then
      raise exception 'Inventory not found for inbound revert.';
    end if;

    if v_current_quantity < v_new_quantity then
      raise exception 'Insufficient inventory to revert inbound transaction.';
    end if;

    update public.inventory
    set quantity = quantity - v_new_quantity,
        updated_at = timezone('utc', now())
    where user_id = v_user_id
      and model_id = v_transaction.model_id
      and size_id = v_transaction.size_id
      and color_id = v_transaction.color_id
      and warehouse_id = v_transaction.warehouse_id;
  elsif v_transaction.type = 'OUTBOUND' then
    v_new_type := 'INBOUND';
    v_new_quantity := v_transaction.quantity;

    insert into public.inventory (
      user_id, model_id, size_id, color_id, warehouse_id, quantity
    )
    values (
      v_user_id,
      v_transaction.model_id,
      v_transaction.size_id,
      v_transaction.color_id,
      v_transaction.warehouse_id,
      v_new_quantity
    )
    on conflict (user_id, model_id, size_id, color_id, warehouse_id)
    do update
      set quantity = public.inventory.quantity + excluded.quantity,
          updated_at = timezone('utc', now());
  else
    v_new_type := 'ADJUSTMENT';

    for v_previous in
      select *
      from public.transactions prior
      where prior.user_id = v_user_id
        and prior.model_id = v_transaction.model_id
        and prior.size_id = v_transaction.size_id
        and prior.color_id = v_transaction.color_id
        and prior.warehouse_id = v_transaction.warehouse_id
        and (
          prior.date < v_transaction.date
          or (prior.date = v_transaction.date and prior.created_at < v_transaction.created_at)
          or (
            prior.date = v_transaction.date
            and prior.created_at = v_transaction.created_at
            and prior.id < v_transaction.id
          )
        )
      order by prior.date asc, prior.created_at asc, prior.id asc
    loop
      if v_previous.type = 'INBOUND' then
        v_running_quantity := v_running_quantity + v_previous.quantity;
      elsif v_previous.type = 'OUTBOUND' then
        v_running_quantity := greatest(v_running_quantity - v_previous.quantity, 0);
      else
        v_running_quantity := v_previous.quantity;
      end if;
    end loop;

    v_new_quantity := v_running_quantity;

    insert into public.inventory (
      user_id, model_id, size_id, color_id, warehouse_id, quantity
    )
    values (
      v_user_id,
      v_transaction.model_id,
      v_transaction.size_id,
      v_transaction.color_id,
      v_transaction.warehouse_id,
      v_new_quantity
    )
    on conflict (user_id, model_id, size_id, color_id, warehouse_id)
    do update
      set quantity = excluded.quantity,
          updated_at = timezone('utc', now());
  end if;

  insert into public.transactions (
    user_id,
    date,
    model_id,
    size_id,
    color_id,
    type,
    quantity,
    warehouse_id,
    source_channel,
    reference_type,
    reference_id,
    memo
  )
  values (
    v_user_id,
    current_date,
    v_transaction.model_id,
    v_transaction.size_id,
    v_transaction.color_id,
    v_new_type,
    v_new_quantity,
    v_transaction.warehouse_id,
    'history-revert',
    'transaction_revert',
    v_transaction.id,
    coalesce(v_normalized_memo, '이력 되돌리기')
  )
  returning id into v_new_transaction_id;

  return v_new_transaction_id;
end;
$$;

create or replace function public.receive_factory_arrival(
  p_arrival_id bigint,
  p_warehouse_id bigint,
  p_items jsonb
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_item jsonb;
  v_arrival public.factory_arrivals%rowtype;
  v_arrival_item public.factory_arrival_items%rowtype;
  v_model_id bigint;
  v_size_id bigint;
  v_color_id bigint;
  v_quantity integer;
  v_remaining integer;
  v_total_remaining integer;
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  select *
  into v_arrival
  from public.factory_arrivals
  where id = p_arrival_id
    and user_id = v_user_id
  for update;

  if not found then
    raise exception 'Factory arrival not found.';
  end if;

  if v_arrival.status in ('RECEIVED', 'VARIANCE_CLOSED', 'CANCELLED') then
    raise exception 'This arrival cannot be received.';
  end if;

  if jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'p_items must be a JSON array.';
  end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    select *
    into v_arrival_item
    from public.factory_arrival_items
    where id = (v_item ->> 'arrival_item_id')::bigint
      and factory_arrival_id = p_arrival_id
      and user_id = v_user_id
    for update;

    if not found then
      raise exception 'Factory arrival item not found.';
    end if;

    v_quantity := (v_item ->> 'quantity')::integer;
    v_remaining := v_arrival_item.ordered_quantity - v_arrival_item.received_quantity;

    if v_quantity is null or v_quantity <= 0 then
      raise exception 'Receive quantity must be greater than zero.';
    end if;

    if v_quantity > v_remaining then
      raise exception 'Receive quantity exceeds remaining quantity.';
    end if;

    v_model_id := v_arrival_item.model_id;
    v_size_id := v_arrival_item.size_id;
    v_color_id := v_arrival_item.color_id;

    update public.factory_arrival_items
    set received_quantity = received_quantity + v_quantity,
        updated_at = timezone('utc', now())
    where id = v_arrival_item.id
      and user_id = v_user_id;

    insert into public.inventory (
      user_id, model_id, size_id, color_id, warehouse_id, quantity
    )
    values (
      v_user_id, v_model_id, v_size_id, v_color_id, p_warehouse_id, v_quantity
    )
    on conflict (user_id, model_id, size_id, color_id, warehouse_id)
    do update
      set quantity = public.inventory.quantity + excluded.quantity,
          updated_at = timezone('utc', now());

    insert into public.transactions (
      user_id, date, model_id, size_id, color_id, type, quantity, warehouse_id, source_channel, reference_type, reference_id, memo
    )
    values (
      v_user_id,
      current_date,
      v_model_id,
      v_size_id,
      v_color_id,
      'INBOUND',
      v_quantity,
      p_warehouse_id,
      'factory-arrival',
      'factory_arrival',
      p_arrival_id,
      coalesce(v_arrival.memo, '공장 예정 입고 반영')
    );
  end loop;

  select coalesce(sum(ordered_quantity - received_quantity), 0)
  into v_total_remaining
  from public.factory_arrival_items
  where factory_arrival_id = p_arrival_id
    and user_id = v_user_id;

  update public.factory_arrivals
  set status = case
      when v_total_remaining = 0 then 'RECEIVED'
      else 'PARTIAL'
    end,
    updated_at = timezone('utc', now())
  where id = p_arrival_id
    and user_id = v_user_id;
end;
$$;

