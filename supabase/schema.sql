 perform private.refresh_factory_arrival_status(a.id,u); return jsonb_build_object('arrival_id',a.id,'item_id',i.id);
end $$;

create or replace function public.move_factory_arrival_remainders_to_warehouse(p_payload jsonb) returns jsonb language plpgsql security definer set search_path=private,public as $$
declare u uuid:=auth.uid(); a public.factory_arrivals%rowtype; i public.factory_arrival_items%rowtype; target bigint:=(p_payload->>'warehouse_id')::bigint; before_rows jsonb; after_rows jsonb; fixed_total integer; target_fixed integer; movable integer; allocation_total integer; changed integer:=0;
begin
 if u is null or target is null or btrim(coalesce(p_payload->>'reason',''))='' then raise exception 'Invalid move-all allocation request.'; end if;
 if not exists(select 1 from public.warehouses where id=target and user_id=u) then raise exception 'Warehouse not found.'; end if;
 select * into a from public.factory_arrivals where id=(p_payload->>'arrival_id')::bigint and user_id=u for update; if not found or a.status in('RECEIVED','VARIANCE_CLOSED','CANCELLED') then raise exception 'Arrival cannot be reallocated.'; end if;
 perform 1 from public.factory_arrival_items where factory_arrival_id=a.id and user_id=u order by id for update;
 perform 1 from public.factory_arrival_allocations where factory_arrival_id=a.id and user_id=u order by id for update;
 if exists(select 1 from public.factory_arrival_items where factory_arrival_id=a.id and user_id=u) and not exists(select 1 from public.factory_arrival_items current_item where current_item.factory_arrival_id=a.id and current_item.user_id=u and (exists(select 1 from public.factory_arrival_allocations current_allocation where current_allocation.factory_arrival_item_id=current_item.id and current_allocation.user_id=u and current_allocation.allocated_quantity<>(current_allocation.normally_received_quantity+current_allocation.shortage_closed_quantity+case when current_allocation.warehouse_id=target then current_item.ordered_quantity-coalesce((select sum(fixed_allocation.normally_received_quantity+fixed_allocation.shortage_closed_quantity) from public.factory_arrival_allocations fixed_allocation where fixed_allocation.factory_arrival_item_id=current_item.id and fixed_allocation.user_id=u),0) else 0 end)) or (current_item.ordered_quantity-coalesce((select sum(fixed_allocation.normally_received_quantity+fixed_allocation.shortage_closed_quantity) from public.factory_arrival_allocations fixed_allocation where fixed_allocation.factory_arrival_item_id=current_item.id and fixed_allocation.user_id=u),0)>0 and not exists(select 1 from public.factory_arrival_allocations target_allocation where target_allocation.factory_arrival_item_id=current_item.id and target_allocation.user_id=u and target_allocation.warehouse_id=target)))) then return jsonb_build_object('arrival_id',a.id,'changed_item_count',0,'unchanged',true); end if;
 for i in select * from public.factory_arrival_items where factory_arrival_id=a.id and user_id=u order by id for update loop
  if i.product_variant_id is null or i.ordered_quantity is null then raise exception 'Arrival item not found.'; end if;
  perform 1 from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u order by id for update;
  select coalesce(jsonb_agg(jsonb_build_object('allocation_id',id,'warehouse_id',warehouse_id,'allocated_quantity',allocated_quantity,'normally_received_quantity',normally_received_quantity,'shortage_closed_quantity',shortage_closed_quantity) order by warehouse_id),'[]'::jsonb),coalesce(sum(normally_received_quantity+shortage_closed_quantity),0),coalesce(sum(case when warehouse_id=target then normally_received_quantity+shortage_closed_quantity else 0 end),0) into before_rows,fixed_total,target_fixed from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u;
  movable:=i.ordered_quantity-fixed_total; if movable<0 then raise exception 'Allocation fixed quantity invariant failed.'; end if;
  delete from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u and normally_received_quantity+shortage_closed_quantity=0;
  update public.factory_arrival_allocations set allocated_quantity=normally_received_quantity+shortage_closed_quantity,updated_at=timezone('utc',now()) where factory_arrival_item_id=i.id and user_id=u;
  if movable>0 then
   update public.factory_arrival_allocations set allocated_quantity=target_fixed+movable,warehouse_name_snapshot=(select name from public.warehouses where id=target and user_id=u),updated_at=timezone('utc',now()) where factory_arrival_item_id=i.id and user_id=u and warehouse_id=target;
   if not found then insert into public.factory_arrival_allocations(user_id,factory_arrival_id,factory_arrival_item_id,product_variant_id,warehouse_id,allocated_quantity,warehouse_name_snapshot) values(u,a.id,i.id,i.product_variant_id,target,movable,(select name from public.warehouses where id=target and user_id=u)); end if;
  end if;
  select coalesce(sum(allocated_quantity),0),coalesce(jsonb_agg(jsonb_build_object('allocation_id',id,'warehouse_id',warehouse_id,'allocated_quantity',allocated_quantity,'normally_received_quantity',normally_received_quantity,'shortage_closed_quantity',shortage_closed_quantity) order by warehouse_id),'[]'::jsonb) into allocation_total,after_rows from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u;
  if allocation_total<>i.ordered_quantity then raise exception 'Allocation sum invariant failed.'; end if;
  if before_rows is distinct from after_rows then insert into public.factory_arrival_allocation_audits(user_id,factory_arrival_id,factory_arrival_item_id,before_allocations,after_allocations,reason,actor_id) values(u,a.id,i.id,before_rows,after_rows,btrim(p_payload->>'reason'),u); changed:=changed+1; end if;
 end loop;
 perform private.refresh_factory_arrival_status(a.id,u); return jsonb_build_object('arrival_id',a.id,'changed_item_count',changed);
end $$;
