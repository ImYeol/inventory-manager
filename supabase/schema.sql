create or replace function private.refresh_factory_arrival_status(p_arrival_id bigint,p_user_id uuid) returns void language plpgsql set search_path=private,public as $$
declare v_has_receipt boolean; v_has_remainder boolean; v_has_variance boolean;
begin
  select exists(select 1 from public.factory_receipt_lines l join public.factory_receipt_events e on e.id=l.factory_receipt_event_id and e.user_id=l.user_id where e.factory_arrival_id=p_arrival_id and l.user_id=p_user_id and not exists(select 1 from public.factory_receipt_line_corrections c where c.factory_receipt_line_id=l.id and c.user_id=l.user_id)) into v_has_receipt;
  select exists(select 1 from public.factory_arrival_allocations x where x.factory_arrival_id=p_arrival_id and x.user_id=p_user_id and x.normally_received_quantity+x.shortage_closed_quantity<x.allocated_quantity) into v_has_remainder;
  select exists(select 1 from public.factory_arrival_shortage_closures c join public.factory_arrival_allocations x on x.id=c.factory_arrival_allocation_id and x.user_id=c.user_id where x.factory_arrival_id=p_arrival_id and c.user_id=p_user_id)
      or exists(select 1 from public.factory_receipt_lines l join public.factory_receipt_events e on e.id=l.factory_receipt_event_id and e.user_id=l.user_id where e.factory_arrival_id=p_arrival_id and l.user_id=p_user_id and l.overage_quantity>0 and not exists(select 1 from public.factory_receipt_line_corrections c where c.factory_receipt_line_id=l.id and c.user_id=l.user_id)) into v_has_variance;
  update public.factory_arrivals set status=case
    when exists(select 1 from public.factory_arrival_items i where i.factory_arrival_id=p_arrival_id and i.user_id=p_user_id and (i.product_variant_id is null or i.ordered_quantity is null or coalesce((select sum(x.allocated_quantity) from public.factory_arrival_allocations x where x.factory_arrival_item_id=i.id and x.user_id=i.user_id),0)<>i.ordered_quantity)) then 'DRAFT'
    when v_has_remainder then case when v_has_receipt then 'PARTIAL' else 'READY' end when v_has_variance then 'VARIANCE_CLOSED' when v_has_receipt then 'RECEIVED' else 'READY' end,updated_at=timezone('utc',now()) where id=p_arrival_id and user_id=p_user_id;
end $$;

create or replace function private.guard_active_inventory_reservation() returns trigger language plpgsql set search_path=private,public as $$
declare v public.product_variants%rowtype; on_hand integer; committed integer;
begin
  if new.status<>'active' then return new; end if;
  select * into v from public.product_variants where id=new.product_variant_id and user_id=new.user_id; if not found then raise exception 'ProductVariant not found.'; end if;
  select quantity into on_hand from public.inventory where user_id=new.user_id and model_id=v.model_id and size_id=v.size_id and color_id=v.color_id and warehouse_id=new.warehouse_id for update;
  select coalesce(sum(quantity),0) into committed from public.inventory_reservations where user_id=new.user_id and product_variant_id=new.product_variant_id and warehouse_id=new.warehouse_id and status='active' and id<>coalesce(new.id,0);
  if coalesce(on_hand,0)<committed+new.quantity then raise exception 'reservation_exceeds_on_hand'; end if; return new;
end $$;
create trigger inventory_reservation_on_hand_guard before insert or update of product_variant_id,warehouse_id,quantity,status on public.inventory_reservations for each row execute function private.guard_active_inventory_reservation();

create or replace function private.enqueue_factory_variant(p_user_id uuid,p_variant_id bigint) returns void language plpgsql set search_path=private,public as $$
declare v_on_hand integer; v_committed integer; v_target integer; r record;
begin
  select coalesce(sum(i.quantity),0) into v_on_hand from public.inventory i join public.product_variants v on v.model_id=i.model_id and v.size_id=i.size_id and v.color_id=i.color_id and v.user_id=i.user_id where v.id=p_variant_id and i.user_id=p_user_id;
  select coalesce(sum(quantity),0) into v_committed from public.inventory_reservations where user_id=p_user_id and product_variant_id=p_variant_id and status='active';
  v_target:=greatest(0,v_on_hand-v_committed);
  for r in select id from public.channel_product_refs where user_id=p_user_id and variant_id=p_variant_id loop
    insert into public.inventory_sync_outbox(user_id,channel_product_ref_id,target_quantity,status,last_error,requested_at,updated_at) values(p_user_id,r.id,v_target,'required','동기화 필요: 현재 provider는 재고 수량 쓰기를 지원하지 않습니다.',timezone('utc',now()),timezone('utc',now())) on conflict(user_id,channel_product_ref_id) do update set target_quantity=excluded.target_quantity,status='required',last_error=excluded.last_error,requested_at=excluded.requested_at,updated_at=excluded.updated_at;
  end loop;
end $$;

create or replace function public.replace_factory_arrival_allocations(p_payload jsonb) returns jsonb language plpgsql security definer set search_path=private,public as $$
declare u uuid:=auth.uid(); a public.factory_arrivals%rowtype; i public.factory_arrival_items%rowtype; r jsonb; total integer:=0; seen bigint[]:='{}'; desired integer; x public.factory_arrival_allocations%rowtype;
begin
  if u is null or jsonb_typeof(p_payload->'allocations')<>'array' then raise exception 'Invalid allocation request.'; end if;
  select * into a from public.factory_arrivals where id=(p_payload->>'arrival_id')::bigint and user_id=u for update;
  if not found or a.status in('RECEIVED','VARIANCE_CLOSED','CANCELLED') then raise exception 'Arrival cannot be reallocated.'; end if;
  select * into i from public.factory_arrival_items where id=(p_payload->>'item_id')::bigint and factory_arrival_id=a.id and user_id=u for update;
  if not found or i.product_variant_id is null or i.ordered_quantity is null then raise exception 'Arrival item not found.'; end if;
  perform 1 from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u order by id for update;
  for r in select value from jsonb_array_elements(p_payload->'allocations') loop
    if (r->>'warehouse_id')::bigint=any(seen) or coalesce((r->>'quantity')::integer,0)<=0 then raise exception 'Invalid allocation split.'; end if;
    if not exists(select 1 from public.warehouses where id=(r->>'warehouse_id')::bigint and user_id=u) then raise exception 'Warehouse not found.'; end if;
    seen:=array_append(seen,(r->>'warehouse_id')::bigint); total:=total+(r->>'quantity')::integer;
  end loop;
  if total<>i.ordered_quantity then raise exception 'Allocation total must equal ordered quantity.'; end if;
  for x in select * from public.factory_arrival_allocations where factory_arrival_item_id=i.id and user_id=u loop
    select (value->>'quantity')::integer into desired from jsonb_array_elements(p_payload->'allocations') where (value->>'warehouse_id')::bigint=x.warehouse_id;
    if coalesce(desired,0)<x.normally_received_quantity+x.shortage_closed_quantity then raise exception 'Received or closed allocation quantity cannot be moved.'; end if;
  end loop;
  delete from public.factory_arrival_allocations old_allocation where old_allocation.factory_arrival_item_id=i.id and old_allocation.user_id=u and old_allocation.normally_received_quantity=0 and old_allocation.shortage_closed_quantity=0 and not (old_allocation.warehouse_id=any(seen));
  for r in select value from jsonb_array_elements(p_payload->'allocations') loop
    update public.factory_arrival_allocations set allocated_quantity=(r->>'quantity')::integer,warehouse_name_snapshot=(select name from public.warehouses where id=(r->>'warehouse_id')::bigint and user_id=u),updated_at=timezone('utc',now()) where factory_arrival_item_id=i.id and user_id=u and warehouse_id=(r->>'warehouse_id')::bigint;
    if not found then insert into public.factory_arrival_allocations(user_id,factory_arrival_id,factory_arrival_item_id,product_variant_id,warehouse_id,allocated_quantity,warehouse_name_snapshot) values(u,a.id,i.id,i.product_variant_id,(r->>'warehouse_id')::bigint,(r->>'quantity')::integer,(select name from public.warehouses where id=(r->>'warehouse_id')::bigint and user_id=u)); end if;
  end loop;
  perform private.refresh_factory_arrival_status(a.id,u); return jsonb_build_object('arrival_id',a.id,'item_id',i.id);
end $$;

create or replace function public.receive_factory_arrival_request(p_payload jsonb) returns jsonb language plpgsql security definer set search_path=private,public as $$
declare u uuid:=auth.uid(); request_id text:=btrim(p_payload->>'receipt_request_id'); business_date date:=nullif(p_payload->>'receipt_business_date','')::date; canonical jsonb; hash text; existing public.factory_receipt_requests%rowtype; a public.factory_arrivals%rowtype; line jsonb; x public.factory_arrival_allocations%rowtype; i public.factory_arrival_items%rowtype; v public.product_variants%rowtype; q integer; oq integer; event_id bigint; tx bigint; seen bigint[]:='{}';
begin
  if u is null or coalesce(request_id,'')='' or business_date is null or jsonb_typeof(p_payload->'lines')<>'array' or jsonb_array_length(p_payload->'lines')=0 then raise exception 'Invalid receipt request.'; end if;
  canonical:=jsonb_build_object('arrival_id',(p_payload->>'arrival_id')::bigint,'receipt_business_date',business_date,'lines',p_payload->'lines'); hash:=private.factory_payload_hash(canonical);
  perform pg_advisory_xact_lock(hashtextextended(u::text||':'||request_id,0));
  select * into existing from public.factory_receipt_requests where user_id=u and receipt_request_id=request_id;
  if found then if existing.payload_hash<>hash then raise exception 'receipt_request_conflict'; end if; return jsonb_build_object('receipt_event_id',existing.receipt_event_id,'idempotent',true); end if;
  select * into a from public.factory_arrivals where id=(p_payload->>'arrival_id')::bigint and user_id=u for update;
  if not found or a.status in('RECEIVED','VARIANCE_CLOSED','CANCELLED') then raise exception 'Arrival cannot be received.'; end if;
  for line in select value from jsonb_array_elements(p_payload->'lines') order by (value->>'allocation_id')::bigint loop
    q:=coalesce((line->>'quantity')::integer,0); oq:=coalesce((line->>'overage_quantity')::integer,0);
    if (line->>'allocation_id')::bigint=any(seen) then raise exception 'operation_error:allocation:%:Duplicate receipt allocation.',coalesce(line->>'allocation_id','unknown'); end if; seen:=array_append(seen,(line->>'allocation_id')::bigint);
    select * into x from public.factory_arrival_allocations where id=(line->>'allocation_id')::bigint and factory_arrival_id=a.id and user_id=u for update;
    if not found or q<0 or oq<0 or (q=0 and oq=0) or q>x.allocated_quantity-x.normally_received_quantity-x.shortage_closed_quantity or (oq>0 and btrim(coalesce(line->>'overage_reason',''))='') then raise exception 'operation_error:allocation:%:Invalid receipt line.',coalesce(line->>'allocation_id','unknown'); end if;
  end loop;
  insert into public.factory_receipt_events(user_id,factory_arrival_id,event_kind,received_at,receipt_business_date,immutable_payload,receipt_request_id) values(u,a.id,'RECEIPT',timezone('utc',now()),business_date,canonical,request_id) returning id into event_id;
  insert into public.factory_receipt_requests(user_id,receipt_request_id,payload_hash,factory_arrival_id,immutable_payload,receipt_event_id) values(u,request_id,hash,a.id,canonical,event_id);
  for line in select value from jsonb_array_elements(p_payload->'lines') loop
    q:=coalesce((line->>'quantity')::integer,0); oq:=coalesce((line->>'overage_quantity')::integer,0);
    select * into x from public.factory_arrival_allocations where id=(line->>'allocation_id')::bigint and user_id=u;
    select * into i from public.factory_arrival_items where id=x.factory_arrival_item_id and user_id=u;
    select * into v from public.product_variants where id=x.product_variant_id and user_id=u;
    insert into public.inventory(user_id,model_id,size_id,color_id,warehouse_id,quantity) values(u,v.model_id,v.size_id,v.color_id,x.warehouse_id,q+oq) on conflict(user_id,model_id,size_id,color_id,warehouse_id) do update set quantity=public.inventory.quantity+excluded.quantity,updated_at=timezone('utc',now());
    insert into public.transactions(user_id,date,model_id,size_id,color_id,type,quantity,warehouse_id,source_channel,reference_type,reference_id,memo) values(u,business_date,v.model_id,v.size_id,v.color_id,'INBOUND',q+oq,x.warehouse_id,'factory-arrival','factory_receipt_event',event_id,case when oq>0 then btrim(line->>'overage_reason') else '검수 입고' end) returning id into tx;
    insert into public.factory_receipt_lines(user_id,factory_receipt_event_id,factory_arrival_allocation_id,factory_arrival_item_id,warehouse_id,transaction_id,received_quantity,normal_quantity,overage_quantity,overage_reason,seller_sku_snapshot,product_name_snapshot,option_name_snapshot,warehouse_name_snapshot) values(u,event_id,x.id,i.id,x.warehouse_id,tx,q+oq,q,oq,case when oq>0 then btrim(line->>'overage_reason') end,i.seller_sku_snapshot,i.product_name_snapshot,i.option_name_snapshot,x.warehouse_name_snapshot);
    update public.factory_arrival_allocations set normally_received_quantity=normally_received_quantity+q,updated_at=timezone('utc',now()) where id=x.id;
    update public.factory_arrival_items set received_quantity=received_quantity+q,updated_at=timezone('utc',now()) where id=i.id;
    perform private.enqueue_factory_variant(u,v.id);
  end loop;
  perform private.refresh_factory_arrival_status(a.id,u); return jsonb_build_object('receipt_event_id',event_id,'idempotent',false);
end $$;

create or replace function public.close_factory_arrival_shortage(p_payload jsonb) returns jsonb language plpgsql security definer set search_path=private,public as $$
declare u uuid:=auth.uid(); x public.factory_arrival_allocations%rowtype; q integer:=(p_payload->>'quantity')::integer; closure_id bigint; a public.factory_arrivals%rowtype;
begin
  if u is null or q is null or q<=0 or btrim(coalesce(p_payload->>'reason',''))='' then raise exception 'Invalid shortage closure.'; end if;
  select a0.* into a from public.factory_arrivals a0 join public.factory_arrival_allocations x0 on x0.factory_arrival_id=a0.id and x0.user_id=a0.user_id where x0.id=(p_payload->>'allocation_id')::bigint and a0.user_id=u for update of a0;
  if not found or a.status not in('READY','PARTIAL') then raise exception 'Arrival cannot close a shortage.'; end if;
  select * into x from public.factory_arrival_allocations where id=(p_payload->>'allocation_id')::bigint and user_id=u for update;
  if q>x.allocated_quantity-x.normally_received_quantity-x.shortage_closed_quantity then raise exception 'Shortage exceeds expected remainder.'; end if;
  insert into public.factory_arrival_shortage_closures(user_id,factory_arrival_allocation_id,quantity,reason,actor_id) values(u,x.id,q,btrim(p_payload->>'reason'),u) returning id into closure_id;
  update public.factory_arrival_allocations set shortage_closed_quantity=shortage_closed_quantity+q,updated_at=timezone('utc',now()) where id=x.id;
  perform private.refresh_factory_arrival_status(x.factory_arrival_id,u); return jsonb_build_object('closure_id',closure_id,'allocation_id',x.id);
end $$;

