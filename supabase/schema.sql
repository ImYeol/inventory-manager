declare
  v_user_id uuid := auth.uid();
  v_model_id bigint := (p_transfer ->> 'model_id')::bigint;
  v_size_id bigint := (p_transfer ->> 'size_id')::bigint;
  v_color_id bigint := (p_transfer ->> 'color_id')::bigint;
  v_from_warehouse_id bigint := (p_transfer ->> 'from_warehouse_id')::bigint;
  v_to_warehouse_id bigint := (p_transfer ->> 'to_warehouse_id')::bigint;
  v_quantity integer := (p_transfer ->> 'quantity')::integer;
  v_date date := (p_transfer ->> 'date')::date;
  v_reason text := btrim(coalesce(p_transfer ->> 'reason', ''));
  v_source public.inventory%rowtype;
  v_variant_id bigint;
  v_on_hand integer;
  v_committed integer;
  v_target integer;
  v_ref record;
  v_now timestamptz := timezone('utc', now());
  v_sync_error text := '동기화 필요: 현재 provider는 재고 수량 쓰기를 지원하지 않습니다.';
  v_memo text;
