create or replace function public.finalize_order_fulfillment(p_fulfillment_id bigint)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_fulfillment public.order_fulfillments%rowtype;
  v_reservation public.inventory_reservations%rowtype;
  v_variant public.product_variants%rowtype;
  v_inventory_quantity integer;
begin
  if v_user_id is null then raise exception 'Authentication is required.'; end if;
  select * into v_fulfillment from public.order_fulfillments where id = p_fulfillment_id and user_id = v_user_id for update;
  if not found then raise exception 'Order fulfillment not found.'; end if;
  if v_fulfillment.local_status = 'fulfilled' then return true; end if;
  if v_fulfillment.external_status <> 'success' then raise exception 'External fulfillment has not succeeded.'; end if;
  select * into v_reservation from public.inventory_reservations where id = v_fulfillment.inventory_reservation_id and user_id = v_user_id for update;
  if not found or v_reservation.status <> 'active' then raise exception 'Active inventory reservation not found.'; end if;
  select * into v_variant from public.product_variants where id = v_reservation.product_variant_id and user_id = v_user_id;
  if not found then raise exception 'Product variant not found.'; end if;
  select quantity into v_inventory_quantity from public.inventory where user_id = v_user_id and model_id = v_variant.model_id and size_id = v_variant.size_id and color_id = v_variant.color_id and warehouse_id = v_reservation.warehouse_id for update;
  if not found or v_inventory_quantity < v_reservation.quantity then raise exception 'Insufficient on-hand inventory.'; end if;
  update public.inventory set quantity = quantity - v_reservation.quantity, updated_at = timezone('utc', now()) where user_id = v_user_id and model_id = v_variant.model_id and size_id = v_variant.size_id and color_id = v_variant.color_id and warehouse_id = v_reservation.warehouse_id;
  update public.inventory_reservations set status = 'released', released_at = timezone('utc', now()) where id = v_reservation.id and user_id = v_user_id;
  insert into public.transactions (user_id, date, model_id, size_id, color_id, type, quantity, warehouse_id, source_channel, reference_type, reference_id, memo)
  values (v_user_id, current_date, v_variant.model_id, v_variant.size_id, v_variant.color_id, 'OUTBOUND', v_reservation.quantity, v_reservation.warehouse_id, 'channel-fulfillment', 'order_fulfillment', v_fulfillment.id, coalesce(v_fulfillment.tracking_number, '채널 주문 출고'));
  update public.order_fulfillments set local_status = 'fulfilled', fulfilled_at = timezone('utc', now()), updated_at = timezone('utc', now()), error = null where id = v_fulfillment.id and user_id = v_user_id;
  return true;
end;
$$;
revoke execute on function public.finalize_order_fulfillment(bigint) from public, anon;
grant execute on function public.finalize_order_fulfillment(bigint) to authenticated;

