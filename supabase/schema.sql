create or replace function public.reverse_factory_receipt_line(p_payload jsonb) returns jsonb language plpgsql security definer set search_path=private,public as $$
declare u uuid:=auth.uid(); request_id text:=btrim(p_payload->>'correction_request_id'); canonical jsonb; hash text; existing public.factory_receipt_line_corrections%rowtype; l public.factory_receipt_lines%rowtype; e public.factory_receipt_events%rowtype; i public.factory_arrival_items%rowtype; v public.product_variants%rowtype; inv public.inventory%rowtype; reserved integer; tx bigint; correction_id bigint;
begin
  if u is null or coalesce(request_id,'')='' or btrim(coalesce(p_payload->>'reason',''))='' then raise exception 'Invalid receipt correction.'; end if;
  canonical:=jsonb_build_object('receipt_line_id',(p_payload->>'receipt_line_id')::bigint,'reason',btrim(p_payload->>'reason')); hash:=private.factory_payload_hash(canonical);
  perform pg_advisory_xact_lock(hashtextextended(u::text||':'||request_id,0)); select * into existing from public.factory_receipt_line_corrections where user_id=u and correction_request_id=request_id;
  if found then if existing.payload_hash<>hash then raise exception 'correction_request_conflict'; end if; return jsonb_build_object('correction_id',existing.id,'transaction_id',existing.transaction_id,'idempotent',true); end if;
  select * into l from public.factory_receipt_lines where id=(p_payload->>'receipt_line_id')::bigint and user_id=u for update; if not found then raise exception 'Receipt line not found.'; end if;
  if exists(select 1 from public.factory_receipt_line_corrections where factory_receipt_line_id=l.id and user_id=u) then raise exception 'receipt_line_already_reversed'; end if;
  select * into e from public.factory_receipt_events where id=l.factory_receipt_event_id and user_id=u for update; select * into i from public.factory_arrival_items where id=l.factory_arrival_item_id and user_id=u; select * into v from public.product_variants where id=i.product_variant_id and user_id=u;
  select * into inv from public.inventory where user_id=u and model_id=v.model_id and size_id=v.size_id and color_id=v.color_id and warehouse_id=l.warehouse_id for update;
